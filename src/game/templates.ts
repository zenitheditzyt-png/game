// Helper to calculate Robux reward by difficulty
export function getRobuxRewardForStage(stage: number): number {
  if (stage <= 5) return 5;
  if (stage <= 10) return 10;
  if (stage <= 15) return 25;
  if (stage <= 19) return 50;
  return 100; // Stage 20 final castle!
}

export function getDifficultyForStage(stage: number): StageDifficulty {
  if (stage <= 5) return 'Easy';
  if (stage <= 10) return 'Medium';
  if (stage <= 15) return 'Hard';
  return 'Insane';
}

